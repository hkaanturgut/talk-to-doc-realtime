import "server-only";

export type FetchFn = typeof fetch;

export interface Transcript {
  text: string;
  language: string;
  autoGenerated: boolean;
  durationSeconds?: number;
  title?: string;
  source: "direct" | "relay" | "supadata";
}

/** Provider failure kinds; the chain maps them to YOUTUBE_* error codes. */
export type TranscriptErrorKind = "NO_CAPTIONS" | "UNAVAILABLE" | "BLOCKED" | "TRANSIENT";

export class TranscriptError extends Error {
  constructor(
    readonly kind: TranscriptErrorKind,
    message: string,
    options?: { cause?: unknown },
  ) {
    super(message, options);
    this.name = "TranscriptError";
  }
}

export interface TranscriptProvider {
  readonly name: "direct" | "relay" | "supadata";
  fetch(videoId: string): Promise<Transcript>;
}

export interface TrackInfo {
  languageCode: string;
  isAutoGenerated: boolean;
}

/** English first, then the original (first manual) track, then the first track; manual before auto. */
export function pickTrack(tracks: TrackInfo[]): TrackInfo | undefined {
  const en = (t: TrackInfo) => t.languageCode.toLowerCase().split("-")[0] === "en";
  return (
    tracks.find((t) => en(t) && !t.isAutoGenerated) ??
    tracks.find((t) => en(t)) ??
    tracks.find((t) => !t.isAutoGenerated) ??
    tracks[0]
  );
}

/** Joins caption segments into readable text: one paragraph per ~45 s so the preview isn't one wall. */
export function joinSegments(segments: { text: string; offset: number }[]): string {
  const paragraphs: string[] = [];
  let current: string[] = [];
  let start = segments[0]?.offset ?? 0;
  for (const seg of segments) {
    const text = decodeEntities(seg.text).replace(/\s+/g, " ").trim();
    if (!text) continue;
    if (seg.offset - start > 45 && current.length > 0) {
      paragraphs.push(current.join(" "));
      current = [];
      start = seg.offset;
    }
    current.push(text);
  }
  if (current.length > 0) paragraphs.push(current.join(" "));
  return paragraphs.join("\n\n");
}

function decodeEntities(s: string): string {
  return s
    .replace(/&amp;#39;|&#39;/g, "'")
    .replace(/&amp;quot;|&quot;/g, '"')
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">");
}
