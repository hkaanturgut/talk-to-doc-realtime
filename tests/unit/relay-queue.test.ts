import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { RelayQueue } from "@/server/ingestion/youtube/relay/queue";

const transcript = { text: "elephants", language: "en", autoGenerated: false };

describe("RelayQueue", () => {
  beforeEach(() => vi.useFakeTimers());
  afterEach(() => vi.useRealTimers());

  it("hands a queued job to the next poll and resolves the viewer with the result", async () => {
    const q = new RelayQueue();
    const outcome = q.request("jNQXAC9IVRw");
    const job = await q.next(25_000);
    expect(job).toMatchObject({ videoId: "jNQXAC9IVRw" });
    expect(q.complete({ jobId: job!.jobId, ok: true, transcript })).toBe(true);
    await expect(outcome).resolves.toEqual({ ok: true, transcript });
  });

  it("wakes a waiting poll as soon as a job arrives", async () => {
    const q = new RelayQueue();
    const poll = q.next(25_000);
    void q.request("jNQXAC9IVRw");
    await expect(poll).resolves.toMatchObject({ videoId: "jNQXAC9IVRw" });
  });

  it("returns null when the long poll times out", async () => {
    const q = new RelayQueue();
    const poll = q.next(25_000);
    await vi.advanceTimersByTimeAsync(25_000);
    await expect(poll).resolves.toBeNull();
  });

  it("returns null when the poll is aborted", async () => {
    const q = new RelayQueue();
    const ac = new AbortController();
    const poll = q.next(25_000, ac.signal);
    ac.abort();
    await expect(poll).resolves.toBeNull();
  });

  it("dedupes concurrent requests for the same video", async () => {
    const q = new RelayQueue();
    const a = q.request("jNQXAC9IVRw");
    const b = q.request("jNQXAC9IVRw");
    const job = await q.next(1000);
    q.complete({ jobId: job!.jobId, ok: false, kind: "NO_CAPTIONS" });
    await expect(a).resolves.toEqual({ ok: false, kind: "NO_CAPTIONS" });
    await expect(b).resolves.toEqual({ ok: false, kind: "NO_CAPTIONS" });
    const empty = q.next(1000);
    await vi.advanceTimersByTimeAsync(1000);
    await expect(empty).resolves.toBeNull();
  });

  it("leases each job once, oldest first", async () => {
    const q = new RelayQueue();
    void q.request("aaaaaaaaaaa");
    void q.request("bbbbbbbbbbb");
    expect((await q.next(1000))?.videoId).toBe("aaaaaaaaaaa");
    expect((await q.next(1000))?.videoId).toBe("bbbbbbbbbbb");
  });

  it("refuses jobs over the cap so they skip the relay", async () => {
    const q = new RelayQueue({ maxJobs: 1 });
    void q.request("aaaaaaaaaaa");
    await expect(q.request("bbbbbbbbbbb")).resolves.toEqual({ ok: false, kind: "BLOCKED" });
  });

  it("expires jobs as TRANSIENT and rejects late results", async () => {
    const q = new RelayQueue({ jobTtlMs: 15_000 });
    const outcome = q.request("jNQXAC9IVRw");
    const job = await q.next(1000);
    await vi.advanceTimersByTimeAsync(15_000);
    await expect(outcome).resolves.toEqual({ ok: false, kind: "TRANSIENT" });
    expect(q.complete({ jobId: job!.jobId, ok: true, transcript })).toBe(false);
  });

  it("accepts a result only once and rejects unknown job ids", async () => {
    const q = new RelayQueue();
    void q.request("jNQXAC9IVRw");
    const job = await q.next(1000);
    expect(q.complete({ jobId: job!.jobId, ok: true, transcript })).toBe(true);
    expect(q.complete({ jobId: job!.jobId, ok: true, transcript })).toBe(false);
    expect(q.complete({ jobId: crypto.randomUUID(), ok: true, transcript })).toBe(false);
  });

  it("tracks presence from polls", async () => {
    const q = new RelayQueue({ presenceMs: 30_000 });
    expect(q.online()).toBe(false);
    expect(q.lastSeenSeconds()).toBeNull();
    const poll = q.next(25_000);
    expect(q.online()).toBe(true);
    expect(q.lastSeenSeconds()).toBe(0);
    await vi.advanceTimersByTimeAsync(25_000);
    await poll;
    await vi.advanceTimersByTimeAsync(10_000);
    expect(q.online()).toBe(true);
    expect(q.lastSeenSeconds()).toBe(10);
    await vi.advanceTimersByTimeAsync(21_000);
    expect(q.online()).toBe(false);
  });
});
