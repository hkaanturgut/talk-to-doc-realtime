import "server-only";
import { z } from "zod";
import {
  joinSegments,
  TranscriptError,
  type FetchFn,
  type Transcript,
  type TranscriptProvider,
} from "../types";

const BASE = "https://api.supadata.ai/v1/youtube/transcript";

const Segment = z.object({ text: z.string(), offset: z.number(), duration: z.number().optional() });
const Response = z.object({
  content: z.union([z.string(), z.array(Segment)]),
  lang: z.string().optional(),
  availableLangs: z.array(z.string()).optional(),
});

/**
 * Optional hosted fallback (bonus, research R8): a caption API that works from cloud IPs.
 * Enabled only when SUPADATA_API_KEY is set; calls a fixed host, response validated with zod.
 */
export class SupadataProvider implements TranscriptProvider {
  readonly name = "supadata" as const;
  constructor(
    private readonly apiKey: string,
    private readonly fetchFn: FetchFn = fetch,
  ) {}

  async fetch(videoId: string): Promise<Transcript> {
    let res: globalThis.Response;
    try {
      res = await this.fetchFn(`${BASE}?videoId=${encodeURIComponent(videoId)}&lang=en`, {
        headers: { "x-api-key": this.apiKey },
        signal: AbortSignal.timeout(15_000),
      });
    } catch (cause) {
      throw new TranscriptError("TRANSIENT", "supadata request failed", { cause });
    }
    if (res.status === 404) throw new TranscriptError("UNAVAILABLE", "supadata 404");
    if (res.status === 206 || res.status === 422)
      throw new TranscriptError("NO_CAPTIONS", `supadata ${res.status}`);
    if (!res.ok) throw new TranscriptError("TRANSIENT", `supadata ${res.status}`);

    const parsed = Response.safeParse(await res.json().catch(() => null));
    if (!parsed.success) throw new TranscriptError("TRANSIENT", "supadata response did not match schema");
    const { content, lang } = parsed.data;
    const text =
      typeof content === "string"
        ? content.trim()
        : joinSegments(content.map((s) => ({ ...s, offset: s.offset / 1000 })));
    if (!text) throw new TranscriptError("NO_CAPTIONS", "supadata empty");
    const last = Array.isArray(content) ? content.at(-1) : undefined;
    return {
      text,
      language: lang ?? "en",
      autoGenerated: false,
      durationSeconds: last ? (last.offset + (last.duration ?? 0)) / 1000 : undefined,
      source: "supadata",
    };
  }
}
