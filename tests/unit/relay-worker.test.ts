import { describe, expect, it, vi } from "vitest";
import { TranscriptError } from "@/server/ingestion/youtube/types";
import { pollOnce, type WorkerDeps } from "../../tools/caption-relay/worker";

const SECRET = "s".repeat(44);
const JOB = { jobId: crypto.randomUUID(), videoId: "jNQXAC9IVRw" };
const TEXT = "the cool thing about these guys is that they have really really long trunks";

function setup(provider: WorkerDeps["provider"]["fetch"], next: () => Response | Promise<Response>) {
  const posted: unknown[] = [];
  const lines: string[] = [];
  const fetchFn = vi.fn(async (url: string | URL | Request, init?: RequestInit) => {
    const u = String(url);
    expect(new Headers(init?.headers).get("authorization")).toBe(`Bearer ${SECRET}`);
    if (u.endsWith("/api/relay/next")) return next();
    posted.push(JSON.parse(String(init?.body)));
    return new Response(null, { status: 204 });
  }) as unknown as typeof fetch;
  const deps = {
    appUrl: "https://app.example",
    secret: SECRET,
    provider: { fetch: vi.fn(provider) },
    fetchFn,
    log: (l: string) => lines.push(l),
  };
  return { deps, posted, lines };
}

describe("caption relay worker", () => {
  it("fetches captions for a job and posts an ok result", async () => {
    const { deps, posted, lines } = setup(
      async () => ({
        text: TEXT,
        language: "en",
        autoGenerated: false,
        durationSeconds: 19,
        title: "Me at the zoo",
        source: "direct",
      }),
      () => Response.json(JOB),
    );
    await expect(pollOnce(deps, 0)).resolves.toEqual({ delayMs: 0, failed: false });
    expect(posted).toEqual([
      {
        jobId: JOB.jobId,
        ok: true,
        transcript: {
          text: TEXT,
          language: "en",
          autoGenerated: false,
          durationSeconds: 19,
          title: "Me at the zoo",
        },
      },
    ]);
    expect(lines.join("\n")).toMatch(/jNQXAC9IVRw ok/);
    expect(lines.join("\n")).not.toContain("trunks");
    expect(lines.join("\n")).not.toContain(SECRET);
  });

  it("maps provider errors to failure kinds", async () => {
    const { deps, posted } = setup(
      () => Promise.reject(new TranscriptError("NO_CAPTIONS", "none")),
      () => Response.json(JOB),
    );
    await pollOnce(deps, 0);
    expect(posted).toEqual([{ jobId: JOB.jobId, ok: false, kind: "NO_CAPTIONS" }]);
  });

  it("maps unknown errors to TRANSIENT", async () => {
    const { deps, posted } = setup(
      () => Promise.reject(new Error("boom")),
      () => Response.json(JOB),
    );
    await pollOnce(deps, 0);
    expect(posted).toEqual([{ jobId: JOB.jobId, ok: false, kind: "TRANSIENT" }]);
  });

  it("polls again at once after 204", async () => {
    const { deps } = setup(
      () => Promise.reject(new Error("unused")),
      () => new Response(null, { status: 204 }),
    );
    await expect(pollOnce(deps, 3)).resolves.toEqual({ delayMs: 0, failed: false });
  });

  it("backs off after network errors and bad statuses, capped at 30 s", async () => {
    const down = setup(
      () => Promise.reject(new Error("unused")),
      () => Promise.reject(new TypeError("fetch failed")),
    );
    await expect(pollOnce(down.deps, 0)).resolves.toEqual({ delayMs: 1000, failed: true });
    await expect(pollOnce(down.deps, 2)).resolves.toEqual({ delayMs: 4000, failed: true });
    await expect(pollOnce(down.deps, 10)).resolves.toEqual({ delayMs: 30_000, failed: true });
    const denied = setup(
      () => Promise.reject(new Error("unused")),
      () => new Response(null, { status: 401 }),
    );
    await expect(pollOnce(denied.deps, 0)).resolves.toMatchObject({ failed: true });
    expect(denied.lines.join()).toMatch(/401 \(wrong secret\?\)/);
  });

  it("ignores malformed jobs without calling YouTube", async () => {
    const { deps, posted } = setup(
      () => Promise.reject(new Error("unused")),
      () => Response.json({ jobId: "x", videoId: "../../etc" }),
    );
    await expect(pollOnce(deps, 0)).resolves.toEqual({ delayMs: 0, failed: false });
    expect(deps.provider.fetch).not.toHaveBeenCalled();
    expect(posted).toEqual([]);
  });
});
