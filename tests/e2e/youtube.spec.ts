import { expect, test } from "@playwright/test";

const preview = {
  documentId: "11111111-1111-4111-8111-111111111111",
  kind: "youtube",
  title: "Never Gonna Give You Up",
  charCount: 2000,
  estimatedTokens: 500,
  truncated: false,
  usedRatio: 1,
  contextText: "We're no strangers to love...",
  fullTextTail: "",
  videoId: "dQw4w9WgXcQ",
  durationSeconds: 213,
  captionLanguage: "en",
  captionSource: "direct",
  autoGenerated: false,
};

test("YouTube link loads a captioned video", async ({ page }) => {
  await page.route("**/api/ingest/youtube", (route) => route.fulfill({ json: preview }));
  await page.goto("/");
  await page.getByRole("tab", { name: "YouTube" }).click();
  await page.getByLabel("YouTube link").fill("https://youtu.be/dQw4w9WgXcQ?si=abc");
  await page.getByRole("button", { name: "Load video" }).click();
  const region = page.getByRole("region", { name: "Document preview" });
  await expect(region.getByRole("heading", { name: "Never Gonna Give You Up" })).toBeVisible();
  await expect(region).toContainText("3:33");
  await expect(region).toContainText("captions: en");
});

test("blocked captions open the paste fallback, which produces a preview", async ({ page }) => {
  await page.route("**/api/ingest/youtube", (route) =>
    route.fulfill({
      status: 502,
      json: {
        error: {
          code: "YOUTUBE_BLOCKED",
          message: "Captions could not be fetched from here. Paste the transcript instead.",
          retryable: false,
        },
      },
    }),
  );
  await page.goto("/");
  await page.getByRole("tab", { name: "YouTube" }).click();
  await page.getByLabel("YouTube link").fill("https://www.youtube.com/watch?v=dQw4w9WgXcQ");
  await page.getByRole("button", { name: "Load video" }).click();

  await expect(page.getByRole("tab", { name: "Paste text" })).toHaveAttribute("aria-selected", "true");
  await expect(page.getByText("Captions could not be fetched from here")).toBeVisible();

  // real /api/ingest/text route
  await page.getByLabel("Transcript or text").fill("Atlantis transcript: the capital is Poseidonia.");
  await page.getByRole("button", { name: "Use this text" }).click();
  const region = page.getByRole("region", { name: "Document preview" });
  await expect(region.getByRole("heading", { name: "Pasted transcript" })).toBeVisible();
});

test("invalid link shows the inline hint", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("tab", { name: "YouTube" }).click();
  await page.getByLabel("YouTube link").fill("https://vimeo.com/123");
  await expect(page.getByText("Paste a youtube.com or youtu.be link.")).toBeVisible();
});
