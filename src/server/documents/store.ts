import "server-only";
import type { Kind } from "@/shared/schemas";

export interface SourceDocument {
  id: string;
  kind: Kind;
  title: string;
  fullText: string;
  contextText: string;
  charCount: number;
  estimatedTokens: number;
  truncated: boolean;
  usedRatio: number;
  pageCount?: number;
  pagesUsed?: number;
  videoId?: string;
  durationSeconds?: number;
  captionLanguage?: string;
  captionSource?: "direct" | "relay" | "supadata";
  autoGenerated?: boolean;
  sourceUrl?: string;
  createdAt: number;
  lastUsedAt: number;
}

export interface DocumentStore {
  put(doc: SourceDocument): void;
  /** Returns the document and refreshes its idle TTL, or undefined if missing or expired. */
  get(id: string): SourceDocument | undefined;
  readonly size: number;
}

export interface StoreOptions {
  ttlMs?: number;
  maxDocs?: number;
  maxBytes?: number;
  now?: () => number;
}

/** Approximate memory cost of a document's text (UTF-16 code units, 2 bytes each). */
function costOf(doc: SourceDocument): number {
  return (doc.fullText.length + doc.contextText.length) * 2;
}

/** Map-backed store: idle TTL refreshed on read, LRU eviction by count and bytes. */
export class InMemoryDocumentStore implements DocumentStore {
  private readonly docs = new Map<string, SourceDocument>();
  private bytes = 0;
  private readonly ttlMs: number;
  private readonly maxDocs: number;
  private readonly maxBytes: number;
  private readonly now: () => number;

  constructor(opts: StoreOptions = {}) {
    this.ttlMs = opts.ttlMs ?? 60 * 60_000;
    this.maxDocs = opts.maxDocs ?? 200;
    this.maxBytes = opts.maxBytes ?? 300 * 1024 * 1024;
    this.now = opts.now ?? Date.now;
  }

  get size(): number {
    return this.docs.size;
  }

  put(doc: SourceDocument): void {
    this.remove(doc.id);
    this.docs.set(doc.id, doc);
    this.bytes += costOf(doc);
    this.sweep();
  }

  get(id: string): SourceDocument | undefined {
    const doc = this.docs.get(id);
    if (!doc) return undefined;
    const t = this.now();
    if (t - doc.lastUsedAt > this.ttlMs) {
      this.remove(id);
      return undefined;
    }
    doc.lastUsedAt = t;
    this.docs.delete(id);
    this.docs.set(id, doc); // move to most-recently-used position
    return doc;
  }

  private remove(id: string): void {
    const existing = this.docs.get(id);
    if (!existing) return;
    this.bytes -= costOf(existing);
    this.docs.delete(id);
  }

  private sweep(): void {
    const t = this.now();
    for (const [id, doc] of this.docs) {
      if (t - doc.lastUsedAt > this.ttlMs) this.remove(id);
    }
    while (this.docs.size > this.maxDocs || (this.bytes > this.maxBytes && this.docs.size > 1)) {
      const oldest = this.docs.keys().next().value;
      if (oldest === undefined) break;
      this.remove(oldest);
    }
  }
}
