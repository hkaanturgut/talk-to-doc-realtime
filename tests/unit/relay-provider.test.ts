import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { RelayProvider } from "@/server/ingestion/youtube/providers/relay";
import { RelayQueue } from "@/server/ingestion/youtube/relay/queue";

const transcript = { text: "elephants", language: "en", autoGenerated: true, title: "Me at the zoo" };

describe("RelayProvider", () => {
  beforeEach(() => vi.useFakeTimers());
  afterEach(() => vi.useRealTimers());

  it("fails fast as BLOCKED when no relay is online", async () => {
    const q = new RelayQueue();
    await expect(new RelayProvider(q).fetch("jNQXAC9IVRw")).rejects.toMatchObject({ kind: "BLOCKED" });
  });

  it("returns the relay transcript with source relay", async () => {
    const q = new RelayQueue();
    const poll = q.next(25_000);
    const result = new RelayProvider(q).fetch("jNQXAC9IVRw");
    const job = await poll;
    q.complete({ jobId: job!.jobId, ok: true, transcript });
    await expect(result).resolves.toEqual({ ...transcript, source: "relay" });
  });

  it.each(["NO_CAPTIONS", "UNAVAILABLE", "BLOCKED", "TRANSIENT"] as const)(
    "passes %s through",
    async (kind) => {
      const q = new RelayQueue();
      const poll = q.next(25_000);
      const result = new RelayProvider(q).fetch("jNQXAC9IVRw");
      q.complete({ jobId: (await poll)!.jobId, ok: false, kind });
      await expect(result).rejects.toMatchObject({ kind });
    },
  );

  it("times out as TRANSIENT", async () => {
    const q = new RelayQueue({ jobTtlMs: 15_000 });
    void q.next(25_000);
    const result = new RelayProvider(q).fetch("jNQXAC9IVRw");
    const assertion = expect(result).rejects.toMatchObject({ kind: "TRANSIENT" });
    await vi.advanceTimersByTimeAsync(15_000);
    await assertion;
  });
});
