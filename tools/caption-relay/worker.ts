import { TranscriptError, type Transcript } from "../../src/server/ingestion/youtube/types";
import {
  RelayJobSchema,
  RelayTranscriptSchema,
  type RelayJob,
  type RelayResult,
} from "../../src/shared/schemas";

export interface WorkerDeps {
  appUrl: string;
  secret: string;
  provider: { fetch(videoId: string): Promise<Transcript> };
  fetchFn?: typeof fetch;
  log?: (line: string) => void;
}

const MAX_BACKOFF_MS = 30_000;

/**
 * One poll cycle of the outbound-only caption relay (specs/002-caption-relay). Asks the app for a
 * job, fetches captions from this machine's (residential) IP, posts the result. Returns how long
 * to wait before the next cycle: 0 after a normal poll, growing backoff after failures.
 */
export async function pollOnce(
  deps: WorkerDeps,
  failures: number,
): Promise<{ delayMs: number; failed: boolean }> {
  const { appUrl, secret, fetchFn = fetch, log = console.log } = deps;
  const backoff = () => ({ delayMs: Math.min(MAX_BACKOFF_MS, 1000 * 2 ** failures), failed: true });
  let res: Response;
  try {
    res = await fetchFn(`${appUrl}/api/relay/next`, {
      headers: { authorization: `Bearer ${secret}` },
      signal: AbortSignal.timeout(40_000),
    });
  } catch (err) {
    log(`relay: app unreachable (${(err as Error).message}), retrying`);
    return backoff();
  }
  if (res.status === 204) return { delayMs: 0, failed: false };
  if (res.status !== 200) {
    log(`relay: poll returned ${res.status}${res.status === 401 ? " (wrong secret?)" : ""}, retrying`);
    return backoff();
  }
  const job = RelayJobSchema.safeParse(await res.json().catch(() => null));
  if (!job.success) {
    log("relay: ignored a malformed job");
    return { delayMs: 0, failed: false };
  }
  await handleJob(deps, job.data);
  return { delayMs: 0, failed: false };
}

export async function handleJob(deps: WorkerDeps, job: RelayJob): Promise<void> {
  const { appUrl, secret, provider, fetchFn = fetch, log = console.log } = deps;
  const started = Date.now();
  let result: RelayResult;
  try {
    const t = await provider.fetch(job.videoId);
    const transcript = RelayTranscriptSchema.parse({
      text: t.text,
      language: t.language,
      autoGenerated: t.autoGenerated,
      durationSeconds: t.durationSeconds,
      title: t.title?.slice(0, 300),
    });
    result = { jobId: job.jobId, ok: true, transcript };
  } catch (err) {
    result = { jobId: job.jobId, ok: false, kind: err instanceof TranscriptError ? err.kind : "TRANSIENT" };
  }
  const outcome = result.ok ? "ok" : result.kind;
  try {
    const res = await fetchFn(`${appUrl}/api/relay/result`, {
      method: "POST",
      headers: { authorization: `Bearer ${secret}`, "content-type": "application/json" },
      body: JSON.stringify(result),
      signal: AbortSignal.timeout(15_000),
    });
    const secs = ((Date.now() - started) / 1000).toFixed(1);
    log(
      `relay: ${job.videoId} ${outcome} ${secs}s${res.status === 204 ? "" : ` (app answered ${res.status})`}`,
    );
  } catch (err) {
    log(`relay: ${job.videoId} ${outcome}, result not delivered (${(err as Error).message})`);
  }
}

/** Runs poll cycles until `signal` aborts. */
export async function runWorker(deps: WorkerDeps, signal: AbortSignal): Promise<void> {
  let failures = 0;
  while (!signal.aborted) {
    const { delayMs, failed } = await pollOnce(deps, failures);
    failures = failed ? failures + 1 : 0;
    if (delayMs > 0) await new Promise((r) => setTimeout(r, delayMs));
  }
}
