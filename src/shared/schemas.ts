import { z } from "zod";
import { ERROR_CODES } from "./errors";

export const KindSchema = z.enum(["pdf", "youtube", "text"]);
export type Kind = z.infer<typeof KindSchema>;

export const PreviewSchema = z.object({
  documentId: z.uuid(),
  kind: KindSchema,
  title: z.string().min(1).max(200),
  charCount: z.number().int().nonnegative(),
  estimatedTokens: z.number().int().nonnegative(),
  truncated: z.boolean(),
  usedRatio: z.number().min(0).max(1),
  contextText: z.string(),
  fullTextTail: z.string(),
  pageCount: z.number().int().positive().optional(),
  pagesUsed: z.number().int().positive().optional(),
  videoId: z.string().optional(),
  durationSeconds: z.number().nonnegative().optional(),
  captionLanguage: z.string().optional(),
  captionSource: z.enum(["direct", "supadata"]).optional(),
  autoGenerated: z.boolean().optional(),
  sourceUrl: z.string().optional(),
});
export type PreviewDTO = z.infer<typeof PreviewSchema>;

export const MAX_HISTORY_ITEMS = 40;
export const MAX_HISTORY_CHARS = 8_000;

export const HistoryItemSchema = z.object({
  speaker: z.enum(["user", "assistant"]),
  text: z.string().max(MAX_HISTORY_CHARS),
});
export type HistoryItem = z.infer<typeof HistoryItemSchema>;

export const SessionModeSchema = z.enum(["voice", "text"]);
export type SessionMode = z.infer<typeof SessionModeSchema>;

export const SessionRequestSchema = z.object({
  documentId: z.uuid(),
  mode: SessionModeSchema,
  history: z
    .array(HistoryItemSchema)
    .max(MAX_HISTORY_ITEMS)
    .refine((items) => items.reduce((n, i) => n + i.text.length, 0) <= MAX_HISTORY_CHARS, {
      message: `history exceeds ${MAX_HISTORY_CHARS} chars`,
    })
    .optional(),
});
export type SessionRequest = z.infer<typeof SessionRequestSchema>;

export const SessionResponseSchema = z.object({
  clientSecret: z.string().min(1),
  expiresAt: z.number().int(),
  callsUrl: z.url(),
  model: z.string(),
  provider: z.enum(["azure", "openai"]),
  sessionMaxSeconds: z.number().int().positive(),
});
export type SessionResponse = z.infer<typeof SessionResponseSchema>;

export const ErrorBodySchema = z.object({
  error: z.object({
    code: z.enum(ERROR_CODES),
    message: z.string(),
    retryable: z.boolean(),
  }),
});
export type ErrorBody = z.infer<typeof ErrorBodySchema>;

export const YouTubeRequestSchema = z.object({ url: z.string().min(1).max(2048) });
export const TextRequestSchema = z.object({
  title: z.string().max(200).optional(),
  text: z.string(),
  sourceUrl: z.string().max(2048).optional(),
});
