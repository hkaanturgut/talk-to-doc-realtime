import type { PreviewDTO } from "@/shared/schemas";
import { Icon } from "../ui/Icon";
import { TruncationNotice } from "./TruncationNotice";

export function formatDuration(seconds: number): string {
  const s = Math.round(seconds);
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const sec = String(s % 60).padStart(2, "0");
  return h > 0 ? `${h}:${String(m).padStart(2, "0")}:${sec}` : `${m}:${sec}`;
}

function facts(p: PreviewDTO): string[] {
  const out: string[] = [];
  if (p.kind === "pdf" && p.pageCount) out.push(`${p.pageCount} ${p.pageCount === 1 ? "page" : "pages"}`);
  if (p.kind === "youtube") {
    if (p.durationSeconds) out.push(formatDuration(p.durationSeconds));
    if (p.captionLanguage) out.push(`captions: ${p.captionLanguage}${p.autoGenerated ? " (auto)" : ""}`);
  }
  out.push(`${p.charCount.toLocaleString("en-US")} chars`);
  return out;
}

export function DocumentPreview({ preview, onReplace }: { preview: PreviewDTO; onReplace?: () => void }) {
  return (
    <section
      aria-label="Document preview"
      className="flex flex-col gap-3 rounded-2xl border border-neutral-200 bg-neutral-50 p-4 dark:border-neutral-800 dark:bg-neutral-900"
    >
      <header className="flex items-start gap-3">
        <span className="mt-0.5 rounded-lg bg-indigo-100 p-2 text-indigo-700 dark:bg-indigo-950 dark:text-indigo-300">
          <Icon name={preview.kind} />
        </span>
        <div className="min-w-0 flex-1">
          <h2 className="truncate text-base font-semibold" title={preview.title}>
            {preview.title}
          </h2>
          <p className="text-sm text-neutral-500 dark:text-neutral-400">{facts(preview).join(" · ")}</p>
        </div>
        {onReplace && (
          <button
            type="button"
            onClick={onReplace}
            className="min-h-11 shrink-0 rounded-lg px-3 text-sm font-medium text-indigo-700 dark:text-indigo-300"
          >
            Change
          </button>
        )}
      </header>

      <TruncationNotice preview={preview} />

      <details className="group rounded-xl bg-white dark:bg-neutral-950" data-testid="preview-details">
        <summary className="flex min-h-11 cursor-pointer list-none items-center justify-between px-3 text-sm font-medium">
          <span>Show extracted text</span>
          <span className="text-neutral-400 transition group-open:rotate-180" aria-hidden="true">
            ▾
          </span>
        </summary>
        <div className="max-h-72 overflow-y-auto border-t border-neutral-100 px-3 py-3 text-sm leading-relaxed whitespace-pre-wrap text-neutral-700 dark:border-neutral-800 dark:text-neutral-300">
          {preview.contextText}
          {preview.truncated && (
            <>
              <div className="my-3 flex items-center gap-2 text-xs font-semibold tracking-wide text-amber-700 uppercase dark:text-amber-300">
                <span className="h-px flex-1 bg-amber-300 dark:bg-amber-800" />
                text cut here
                <span className="h-px flex-1 bg-amber-300 dark:bg-amber-800" />
              </div>
              <p className="text-neutral-400 dark:text-neutral-500">{preview.fullTextTail}…</p>
            </>
          )}
        </div>
      </details>
    </section>
  );
}
