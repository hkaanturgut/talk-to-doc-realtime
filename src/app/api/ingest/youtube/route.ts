import { documentStore } from "@/server/documents";
import { createDocument, toPreview } from "@/server/documents/create";
import { requireAccess } from "@/server/access/require";
import { clientIp } from "@/server/http/client-ip";
import { ingestLimiter } from "@/server/http/rate-limit";
import { errorResponse } from "@/server/http/respond";
import { normalizeText } from "@/server/ingestion/normalize";
import {
  canonicalUrl,
  fetchMetadata,
  fetchTranscriptChain,
  getTranscriptProviders,
  parseYouTubeUrl,
} from "@/server/ingestion/youtube";
import { trackEvent } from "@/server/telemetry";
import { YouTubeRequestSchema } from "@/shared/schemas";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

export async function POST(request: Request): Promise<Response> {
  try {
    await requireAccess(request);
    ingestLimiter.check(clientIp(request));
    const { url } = YouTubeRequestSchema.parse(await request.json().catch(() => ({})));
    const videoId = parseYouTubeUrl(url);

    const [transcript, meta] = await Promise.all([
      fetchTranscriptChain(videoId, getTranscriptProviders()),
      fetchMetadata(videoId),
    ]);

    const { doc, tail } = createDocument({
      kind: "youtube",
      title: meta.title !== "YouTube video" ? meta.title : (transcript.title ?? meta.title),
      fullText: normalizeText(transcript.text),
      extra: {
        videoId,
        durationSeconds: transcript.durationSeconds,
        captionLanguage: transcript.language,
        captionSource: transcript.source,
        autoGenerated: transcript.autoGenerated,
        sourceUrl: canonicalUrl(videoId),
      },
    });
    documentStore.put(doc);
    trackEvent("document_ingested", {
      kind: "youtube",
      charCount: doc.charCount,
      truncated: doc.truncated,
      captionSource: transcript.source,
    });
    return Response.json(toPreview(doc, tail));
  } catch (err) {
    return errorResponse(err, "ingest/youtube");
  }
}
