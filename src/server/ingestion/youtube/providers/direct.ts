import "server-only";
import {
  YoutubeTranscript,
  YoutubeTranscriptDisabledError,
  YoutubeTranscriptNotAvailableError,
  YoutubeTranscriptTooManyRequestError,
  YoutubeTranscriptVideoUnavailableError,
  type FetchParams,
} from "youtube-transcript-plus";
import {
  joinSegments,
  pickTrack,
  TranscriptError,
  type FetchFn,
  type Transcript,
  type TranscriptProvider,
} from "../types";

interface Playability {
  status?: string;
  reason?: string;
}

/**
 * Maps library errors plus the captured player playability status to a provider error kind.
 * LOGIN_REQUIRED covers bot checks on cloud IPs and age-restricted videos (indistinguishable).
 */
export function mapDirectError(err: unknown, playability?: Playability): TranscriptError {
  const status = playability?.status;
  const msg = (err as Error)?.message ?? String(err);
  if (err instanceof YoutubeTranscriptTooManyRequestError)
    return new TranscriptError("BLOCKED", msg, { cause: err });
  if (status === "LOGIN_REQUIRED" || /sign in|bot/i.test(playability?.reason ?? "")) {
    return new TranscriptError("BLOCKED", `playability ${status}`, { cause: err });
  }
  if (status === "ERROR" || status === "UNPLAYABLE")
    return new TranscriptError("UNAVAILABLE", msg, { cause: err });
  if (status === "LIVE_STREAM_OFFLINE") return new TranscriptError("NO_CAPTIONS", msg, { cause: err });
  if (err instanceof YoutubeTranscriptVideoUnavailableError)
    return new TranscriptError("UNAVAILABLE", msg, { cause: err });
  if (err instanceof YoutubeTranscriptDisabledError)
    return new TranscriptError("NO_CAPTIONS", msg, { cause: err });
  if (err instanceof YoutubeTranscriptNotAvailableError) {
    // Playable but no tracks → no captions; not playable for an unknown reason → treat as blocked.
    return new TranscriptError(status === "OK" ? "NO_CAPTIONS" : "BLOCKED", msg, { cause: err });
  }
  return new TranscriptError("TRANSIENT", msg, { cause: err });
}

/** Innertube-based captions (youtube-transcript-plus). Works from residential IPs; usually blocked in clouds. */
export class DirectProvider implements TranscriptProvider {
  readonly name = "direct" as const;
  constructor(private readonly fetchFn: FetchFn = fetch) {}

  async fetch(videoId: string): Promise<Transcript> {
    let playability: Playability | undefined;
    const send = (p: FetchParams) =>
      this.fetchFn(p.url, {
        method: p.method ?? "GET",
        body: p.body,
        headers: {
          ...(p.headers ?? {}),
          ...(p.userAgent ? { "User-Agent": p.userAgent } : {}),
          ...(p.lang ? { "Accept-Language": p.lang } : {}),
        },
        signal: p.signal ?? AbortSignal.timeout(10_000),
      });
    const playerFetch = async (p: FetchParams) => {
      const res = await send(p);
      try {
        const json = (await res.clone().json()) as { playabilityStatus?: Playability };
        playability = json.playabilityStatus;
      } catch {
        /* not JSON */
      }
      return res;
    };
    const config = { playerFetch, videoFetch: send, transcriptFetch: send, retries: 1 };

    try {
      const languages = await YoutubeTranscript.listLanguages(videoId, config);
      const track = pickTrack(languages);
      if (!track) throw new TranscriptError("NO_CAPTIONS", "no caption tracks");
      const { segments, videoDetails } = await YoutubeTranscript.fetchTranscript(videoId, {
        ...config,
        lang: track.languageCode,
        videoDetails: true,
      });
      if (videoDetails.isLiveContent && segments.length === 0)
        throw new TranscriptError("NO_CAPTIONS", "live");
      const text = joinSegments(segments);
      if (!text) throw new TranscriptError("NO_CAPTIONS", "empty transcript");
      const last = segments.at(-1);
      return {
        text,
        language: track.languageCode,
        autoGenerated: track.isAutoGenerated,
        durationSeconds: videoDetails.lengthSeconds || (last ? last.offset + last.duration : undefined),
        title: videoDetails.title || undefined,
        source: "direct",
      };
    } catch (err) {
      if (err instanceof TranscriptError) throw err;
      throw mapDirectError(err, playability);
    }
  }
}
