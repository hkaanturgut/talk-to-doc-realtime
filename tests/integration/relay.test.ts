import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { GET as health } from "@/app/api/health/route";
import { POST as ingest } from "@/app/api/ingest/youtube/route";
import { GET as next } from "@/app/api/relay/next/route";
import { POST as result } from "@/app/api/relay/result/route";
import { setTranscriptProvidersForTests } from "@/server/ingestion/youtube";
import { RelayProvider } from "@/server/ingestion/youtube/providers/relay";
import { relayQueue } from "@/server/ingestion/youtube/relay";
import { TranscriptError, type TranscriptProvider } from "@/server/ingestion/youtube/types";
import { PreviewSchema } from "@/shared/schemas";
import { freshIp } from "../support/fixtures";

const SECRET = "r".repeat(44);
const VIDEO = "https://www.youtube.com/watch?v=jNQXAC9IVRw";
const auth = (secret = SECRET) => ({ authorization: `Bearer ${secret}`, "x-forwarded-for": freshIp() });
const blocked: TranscriptProvider = {
  name: "direct",
  fetch: () => Promise.reject(new TranscriptError("BLOCKED", "LOGIN_REQUIRED")),
};

const poll = (headers: HeadersInit = auth()) =>
  next(new Request("http://localhost/api/relay/next", { headers }));
const send = (body: unknown, headers: HeadersInit = auth()) =>
  result(
    new Request("http://localhost/api/relay/result", {
      method: "POST",
      headers: { ...headers, "content-type": "application/json" },
      body: typeof body === "string" ? body : JSON.stringify(body),
    }),
  );
const load = () =>
  ingest(
    new Request("http://localhost/api/ingest/youtube", {
      method: "POST",
      headers: { "content-type": "application/json", "x-forwarded-for": freshIp() },
      body: JSON.stringify({ url: VIDEO }),
    }),
  );

describe("caption relay routes", () => {
  vi.stubGlobal(
    "fetch",
    vi.fn(async () => Response.json({ title: "Me at the zoo", author_name: "jawed" })),
  );
  beforeEach(() => {
    vi.stubEnv("CAPTION_RELAY_SECRET", SECRET);
    setTranscriptProvidersForTests([blocked, new RelayProvider(relayQueue)]);
  });
  afterEach(() => {
    vi.unstubAllEnvs();
    setTranscriptProvidersForTests(undefined);
  });

  it("returns 404 on both routes when the relay is not configured", async () => {
    vi.stubEnv("CAPTION_RELAY_SECRET", "");
    expect((await poll()).status).toBe(404);
    expect((await send({})).status).toBe(404);
    expect(await health().json()).not.toHaveProperty("relay");
  });

  it("rejects a wrong or missing secret with 401, then 429 after repeated failures", async () => {
    const ip = freshIp();
    const wrong = { authorization: `Bearer ${"x".repeat(44)}`, "x-forwarded-for": ip };
    expect((await poll({ "x-forwarded-for": freshIp() })).status).toBe(401);
    const statuses: number[] = [];
    for (let i = 0; i < 11; i++) statuses.push((await poll(wrong)).status);
    expect(statuses.slice(0, 10).every((s) => s === 401)).toBe(true);
    expect(statuses[10]).toBe(429);
    expect((await poll(wrong)).headers.get("cache-control")).toBe("no-store");
  });

  it("falls back to paste fast when no relay is online", async () => {
    const started = Date.now();
    const res = await load();
    expect(res.status).toBe(502);
    expect((await res.json()).error.code).toBe("YOUTUBE_BLOCKED");
    expect(Date.now() - started).toBeLessThan(1000);
  });

  it("loads a blocked video through the relay end to end", async () => {
    const polling = poll();
    expect((await health().json()).relay).toEqual({ online: true, lastSeenSeconds: 0 });
    const loading = load();
    const job = await (await polling).json();
    expect(job).toMatchObject({ videoId: "jNQXAC9IVRw" });
    const text = "All right, so here we are in front of the elephants. They have really long trunks.";
    const accepted = await send({
      jobId: job.jobId,
      ok: true,
      transcript: { text, language: "en", autoGenerated: false },
    });
    expect(accepted.status).toBe(204);
    const res = await loading;
    expect(res.status).toBe(200);
    const preview = PreviewSchema.parse(await res.json());
    expect(preview).toMatchObject({ kind: "youtube", title: "Me at the zoo" });
    expect(preview.contextText).toContain("elephants");
    // Single use: the same result again is rejected.
    expect(
      (await send({ jobId: job.jobId, ok: true, transcript: { text, language: "en", autoGenerated: false } }))
        .status,
    ).toBe(404);
  });

  it("maps a relay NO_CAPTIONS answer to the no-captions message", async () => {
    const polling = poll();
    const loading = load();
    const job = await (await polling).json();
    expect((await send({ jobId: job.jobId, ok: false, kind: "NO_CAPTIONS" })).status).toBe(204);
    const res = await loading;
    expect(res.status).toBe(422);
    expect((await res.json()).error.code).toBe("YOUTUBE_NO_CAPTIONS");
  });

  it("rejects unknown jobs, malformed and oversized bodies", async () => {
    expect((await send({ jobId: crypto.randomUUID(), ok: false, kind: "BLOCKED" })).status).toBe(404);
    expect((await send({ jobId: "nope", ok: true })).status).toBe(400);
    expect((await send("{not json")).status).toBe(400);
    const huge = {
      jobId: crypto.randomUUID(),
      ok: true,
      transcript: { text: "a".repeat(2_200_000), language: "en", autoGenerated: false },
    };
    expect((await send(huge)).status).toBe(400);
  });
});
