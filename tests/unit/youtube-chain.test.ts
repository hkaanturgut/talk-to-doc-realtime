import { describe, expect, it, vi } from "vitest";
import { fetchTranscriptChain } from "@/server/ingestion/youtube";
import { fetchMetadata } from "@/server/ingestion/youtube/metadata";
import {
  joinSegments,
  pickTrack,
  TranscriptError,
  type Transcript,
  type TranscriptProvider,
} from "@/server/ingestion/youtube/types";

const ok: Transcript = { text: "hello", language: "en", autoGenerated: false, source: "direct" };

function provider(name: "direct" | "supadata", impl: () => Promise<Transcript>): TranscriptProvider {
  return { name, fetch: vi.fn(impl) };
}
const failing = (kind: TranscriptError["kind"]) => () => Promise.reject(new TranscriptError(kind, kind));

describe("fetchTranscriptChain", () => {
  it("returns the first success", async () => {
    const a = provider("direct", async () => ok);
    const b = provider("supadata", async () => ({ ...ok, source: "supadata" }));
    await expect(fetchTranscriptChain("id", [a, b])).resolves.toBe(ok);
    expect(b.fetch).not.toHaveBeenCalled();
  });

  it("continues past BLOCKED and TRANSIENT failures", async () => {
    const a = provider("direct", failing("BLOCKED"));
    const b = provider("supadata", async () => ({ ...ok, source: "supadata" }));
    await expect(fetchTranscriptChain("id", [a, b])).resolves.toMatchObject({ source: "supadata" });
    const c = provider("direct", failing("TRANSIENT"));
    await expect(fetchTranscriptChain("id", [c, b])).resolves.toMatchObject({ source: "supadata" });
  });

  it.each([
    ["NO_CAPTIONS", "YOUTUBE_NO_CAPTIONS"],
    ["UNAVAILABLE", "YOUTUBE_UNAVAILABLE"],
  ] as const)("stops on definitive %s", async (kind, code) => {
    const b = provider("supadata", async () => ok);
    await expect(fetchTranscriptChain("id", [provider("direct", failing(kind)), b])).rejects.toMatchObject({
      code,
    });
    expect(b.fetch).not.toHaveBeenCalled();
  });

  it("reports YOUTUBE_BLOCKED when every provider is blocked or failing", async () => {
    await expect(
      fetchTranscriptChain("id", [
        provider("direct", failing("BLOCKED")),
        provider("supadata", failing("TRANSIENT")),
      ]),
    ).rejects.toMatchObject({ code: "YOUTUBE_BLOCKED" });
    await expect(fetchTranscriptChain("id", [])).rejects.toMatchObject({ code: "YOUTUBE_BLOCKED" });
  });
});

describe("pickTrack", () => {
  const t = (languageCode: string, isAutoGenerated: boolean) => ({ languageCode, isAutoGenerated });
  it("prefers manual English, then auto English, then first manual, then first", () => {
    expect(pickTrack([t("tr", false), t("en", true), t("en-GB", false)])).toEqual(t("en-GB", false));
    expect(pickTrack([t("tr", false), t("en", true)])).toEqual(t("en", true));
    expect(pickTrack([t("de", true), t("tr", false)])).toEqual(t("tr", false));
    expect(pickTrack([t("de", true), t("fr", true)])).toEqual(t("de", true));
    expect(pickTrack([])).toBeUndefined();
  });
});

describe("joinSegments", () => {
  it("decodes entities and groups into paragraphs", () => {
    const text = joinSegments([
      { text: "It&#39;s  a", offset: 0 },
      { text: "test", offset: 2 },
      { text: "later", offset: 60 },
    ]);
    expect(text).toBe("It's a test\n\nlater");
  });
});

describe("fetchMetadata", () => {
  it("parses oEmbed", async () => {
    const fetchFn = vi.fn(async () => Response.json({ title: "My Video", author_name: "Chan" }));
    await expect(fetchMetadata("dQw4w9WgXcQ", fetchFn)).resolves.toEqual({
      title: "My Video",
      channel: "Chan",
    });
    expect(String((fetchFn.mock.calls[0] as unknown as [string])[0])).toContain("youtube.com/oembed");
  });
  it("falls back on errors and bad shapes", async () => {
    await expect(
      fetchMetadata(
        "x",
        vi.fn(async () => new Response("", { status: 404 })),
      ),
    ).resolves.toEqual({ title: "YouTube video" });
    await expect(
      fetchMetadata(
        "x",
        vi.fn(async () => Response.json({ nope: 1 })),
      ),
    ).resolves.toEqual({ title: "YouTube video" });
    await expect(
      fetchMetadata(
        "x",
        vi.fn(async () => Promise.reject(new Error("net"))),
      ),
    ).resolves.toEqual({ title: "YouTube video" });
  });
});
