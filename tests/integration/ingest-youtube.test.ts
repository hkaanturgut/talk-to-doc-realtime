import { afterEach, describe, expect, it, vi } from "vitest";
import { POST } from "@/app/api/ingest/youtube/route";
import { setTranscriptProvidersForTests } from "@/server/ingestion/youtube";
import { TranscriptError, type TranscriptProvider } from "@/server/ingestion/youtube/types";
import { PreviewSchema } from "@/shared/schemas";
import { freshIp } from "../support/fixtures";

const URL_OK = "https://youtu.be/dQw4w9WgXcQ?si=x";

function post(body: unknown, ip = freshIp()) {
  return POST(
    new Request("http://localhost/api/ingest/youtube", {
      method: "POST",
      headers: { "content-type": "application/json", "x-forwarded-for": ip },
      body: JSON.stringify(body),
    }),
  );
}

const provider = (impl: TranscriptProvider["fetch"]): TranscriptProvider => ({ name: "direct", fetch: impl });

describe("POST /api/ingest/youtube", () => {
  // oEmbed is the only other network call; stub it.
  vi.stubGlobal(
    "fetch",
    vi.fn(async () => Response.json({ title: "Never Gonna Give You Up", author_name: "Rick Astley" })),
  );
  afterEach(() => setTranscriptProvidersForTests(undefined));

  it("returns a preview with caption language and duration", async () => {
    setTranscriptProvidersForTests([
      provider(async () => ({
        text: "We're no strangers to love",
        language: "en",
        autoGenerated: true,
        durationSeconds: 212,
        source: "direct",
      })),
    ]);
    const res = await post({ url: URL_OK });
    expect(res.status).toBe(200);
    const p = PreviewSchema.parse(await res.json());
    expect(p).toMatchObject({
      kind: "youtube",
      title: "Never Gonna Give You Up",
      videoId: "dQw4w9WgXcQ",
      captionLanguage: "en",
      captionSource: "direct",
      autoGenerated: true,
      durationSeconds: 212,
    });
  });

  it("400 for an invalid URL", async () => {
    const res = await post({ url: "https://evil.com/watch?v=dQw4w9WgXcQ" });
    expect(res.status).toBe(400);
    expect((await res.json()).error.code).toBe("YOUTUBE_INVALID_URL");
  });

  it("400 INVALID_REQUEST for a bad body", async () => {
    expect((await post({ nope: 1 })).status).toBe(400);
  });

  it("422 when the video has no captions", async () => {
    setTranscriptProvidersForTests([provider(() => Promise.reject(new TranscriptError("NO_CAPTIONS", "x")))]);
    const res = await post({ url: URL_OK });
    expect(res.status).toBe(422);
    expect((await res.json()).error.code).toBe("YOUTUBE_NO_CAPTIONS");
  });

  it("502 when all providers are blocked", async () => {
    setTranscriptProvidersForTests([provider(() => Promise.reject(new TranscriptError("BLOCKED", "x")))]);
    const res = await post({ url: URL_OK });
    expect(res.status).toBe(502);
    expect((await res.json()).error.code).toBe("YOUTUBE_BLOCKED");
  });

  it("rate limits to 20 per minute per IP", async () => {
    const ip = freshIp();
    const statuses: number[] = [];
    for (let i = 0; i < 21; i++) statuses.push((await post({ url: "bad" }, ip)).status);
    expect(statuses.slice(0, 20).every((s) => s === 400)).toBe(true);
    expect(statuses[20]).toBe(429);
  });
});
